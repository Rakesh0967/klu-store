// ── Coupon Codes ──────────────────────────────────────────────────────────────
// type: "percent" → discount = subtotal * value / 100
// type: "flat"    → discount = fixed rupee amount
// minOrder: minimum subtotal required to use the coupon
export const COUPONS = {
  KLUFRESH10: { type: "percent", value: 10, minOrder: 0,   desc: "10% off on all orders" },
  SAVE50:     { type: "flat",    value: 50, minOrder: 200,  desc: "₹50 flat off on orders above ₹200" },
  CAMPUS20:   { type: "percent", value: 20, minOrder: 500,  desc: "20% off on orders above ₹500" },
  WELCOME15:  { type: "percent", value: 15, minOrder: 300,  desc: "15% off for new customers (min ₹300)" },
  FREESHIP:   { type: "flat",    value: 30, minOrder: 0,    desc: "₹30 off (free delivery equivalent)" },
};

export const applyCoupon = (code, subtotal) => {
  const coupon = COUPONS[code?.trim().toUpperCase()];
  if (!coupon) return { valid: false, error: "Invalid coupon code." };
  if (subtotal < coupon.minOrder)
    return { valid: false, error: `Minimum order of ₹${coupon.minOrder} required for this coupon.` };
  const saving =
    coupon.type === "percent" ? Math.round((subtotal * coupon.value) / 100) : coupon.value;
  return { valid: true, saving, desc: coupon.desc };
};

export const readStore = (key, fallback) => {
  try {
    const value = localStorage.getItem(key);
    return value === null ? fallback : JSON.parse(value);
  } catch {
    return fallback;
  }
};

export const writeStore = (key, value) => localStorage.setItem(key, JSON.stringify(value));
export const money = value => `₹${Number(value || 0).toLocaleString("en-IN")}`;
